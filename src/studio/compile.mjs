import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseYaml, readBrief, validateStoryboard } from './schema.mjs';
import { formatLint, lint } from './lint.mjs';

const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;

export function compile(project) {
  const root = path.resolve(typeof project === 'string' ? project : project.root);
  const storyboardFile = path.join(root, 'storyboard.yaml');
  if (!fs.existsSync(storyboardFile)) {
    const report = lint(root);
    throw new Error(formatLint({ ...report, errors: report.errors.filter((item) => item.rule === 'schema') }));
  }
  const source = fs.readFileSync(storyboardFile, 'utf8');
  const briefFile = path.join(root, 'brief.md');
  const brief = fs.existsSync(briefFile) ? readBrief(fs.readFileSync(briefFile, 'utf8')).data || {} : {};
  // Errors that make a storyboard unplayable stop the compile; the rest (budgets, pacing) are the
  // lint's to report and `ghostcast next`'s to enforce.
  const report = lint(root);
  const blocking = report.errors.filter((item) => item.file === 'storyboard.yaml' && ['schema', 'surface-change', 'show-surface'].includes(item.rule));
  if (validateStoryboard(source, brief).length || blocking.length) throw new Error(formatLint({ ...report, errors: blocking, warnings: [] }));
  const story = parseYaml(source, 'storyboard.yaml').data;
  const service = (typeof project === 'string' ? null : project.config?.world)?.services?.find((item) => item.port)?.name
    || (() => { const file = path.join(root, 'world.yaml'); return fs.existsSync(file)
      ? parseYaml(fs.readFileSync(file, 'utf8'), 'world.yaml').data?.services?.find((item) => item.port)?.name : null; })();
  const code = [];
  for (const beat of story.beats) {
    if (beat.surface === 'web' && beat.open?.startsWith('/') && !service)
      throw new Error(`${beat.id}: open ${beat.open} needs a world service with port: true`);
    for (const [index, action] of (beat.do || []).entries()) if (action.code) {
      try { new AsyncFunction('h', 'page', action.code); }
      catch (error) { throw new Error(`${beat.id}: code action ${index}: ${error.message}`); }
      code.push(`  ${JSON.stringify(`${beat.id}:${index}`)}: async (h, page) => {\n${action.code.split('\n').map((line) => `    ${line}`).join('\n')}\n  },`);
    }
  }
  const runtime = pathToFileURL(path.resolve(path.dirname(fileURLToPath(import.meta.url)), 'runtime.mjs')).href;
  const module = [
    '// Generated by `ghostcast compile` from storyboard.yaml. Edit the storyboard, not this file.',
    "import fs from 'node:fs';",
    "import path from 'node:path';",
    `import { enter, perform } from ${JSON.stringify(runtime)};`,
    `export const storyboard = ${JSON.stringify(story, null, 2)};`,
    `const code = {${code.length ? `\n${code.join('\n')}\n` : ''}};`,
    'export const beats = storyboard.beats.map((beat) => ({',
    '  id: beat.id,',
    '  enter: (h, previous) => enter(h, beat, previous),',
    '  run: (h) => perform(h, beat, code),',
    '}));',
    'export async function setup(h) { await beats[0].enter(h, null); }',
    'export default async function (h) {',
    '  for (let i = 0; i < beats.length; i++) {',
    '    if (i) await beats[i].enter(h, storyboard.beats[i - 1]);',
    '    await h.seg(beats[i].id, () => beats[i].run(h));',
    '  }',
    '}',
    '',
  ].join('\n');
  const cache = path.join(root, 'cache');
  fs.mkdirSync(cache, { recursive: true });
  fs.writeFileSync(path.join(cache, 'storyboard.mjs'), module);
  fs.writeFileSync(path.join(root, 'timeline.json'), JSON.stringify({ items: [{ take: 'storyboard', scene: 'cache/storyboard.mjs' }] }, null, 2) + '\n');
  return { story, module };
}
